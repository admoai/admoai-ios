#!/usr/bin/env python3
"""Renders the AdMoai module's public symbol graph as one symbol per line.

    Tools/api_render.py <symbolgraph dir> <out.txt>

Reads AdMoai.symbols.json and AdMoai@*.symbols.json (public extensions on other modules'
types) from `swift package dump-symbol-graph --minimum-access-level public`. Each line is
the symbol's path (Type.member), its kind and its declaration as the compiler spells it,
sorted so a type and its members stay together — readable in a PR diff without knowing
Swift. The journey-e2e executable's graph is ignored: it is not shipped.
"""
import glob
import json
import os
import sys

src, out = sys.argv[1:3]
KIND = {
    "swift.class": "class", "swift.struct": "struct", "swift.enum": "enum", "swift.protocol": "protocol",
    "swift.enum.case": "case", "swift.init": "init", "swift.method": "method", "swift.type.method": "static method",
    "swift.property": "property", "swift.type.property": "static property", "swift.func": "func",
    "swift.func.op": "operator", "swift.typealias": "typealias", "swift.subscript": "subscript",
    "swift.associatedtype": "associatedtype", "swift.extension": "extension",
}

lines = set()
files = [os.path.join(src, "AdMoai.symbols.json")] + sorted(glob.glob(os.path.join(src, "AdMoai@*.symbols.json")))
for path in files:
    graph = json.load(open(path))
    extended = os.path.basename(path)[len("AdMoai@"):-len(".symbols.json")] if "@" in path else ""
    for s in graph["symbols"]:
        if s.get("accessLevel") not in ("public", "open"):
            continue
        name = ".".join(s["pathComponents"])
        if extended:
            name = f"{extended}::{name}"
        kind = KIND.get(s["kind"]["identifier"], s["kind"]["identifier"])
        decl = "".join(f["spelling"] for f in s.get("declarationFragments", []))
        decl = " ".join(decl.split())
        deprecated = " [deprecated]" if any(a.get("isUnconditionallyDeprecated") or a.get("deprecated") for a in s.get("availability", [])) else ""
        lines.add(f"{name}  {kind}  {decl}{deprecated}")

header = [
    "# Public API of the AdMoai module — GENERATED by Tools/api.sh, do not edit.",
    "# One symbol per line: path, kind, declaration. A removed or changed line is a breaking",
    "# change (see CONTRIBUTING, \"When the API check fails\").",
]
open(out, "w").write("\n".join(header + sorted(lines)) + "\n")
